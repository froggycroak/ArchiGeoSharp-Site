# 从 ArchiGeoSharp.Raylex XML 注释生成 docs/api/raylex/<Type>.md + 侧栏 manifest
# 依赖全局工具: dotnet tool install -g xmldocmd
# Usage:
#   powershell -File ./scripts/generate-raylex-api.ps1
param(
    [string]$RaylexProjectPath = ""
)

$ErrorActionPreference = "Stop"
$siteRoot = Split-Path $PSScriptRoot -Parent
$docsApi = Join-Path $siteRoot "docs\api"
$raylexRoot = Join-Path $docsApi "raylex"
$sidebarTs = Join-Path $siteRoot "docs\.vitepress\raylex-api-sidebar.ts"
$overviewMd = Join-Path $docsApi "raylex.md"

if (-not $RaylexProjectPath) {
    $RaylexProjectPath = Join-Path $siteRoot "..\ags_v011\src\raylex\ArchiGeoSharp.Raylex.csproj"
    $RaylexProjectPath = [System.IO.Path]::GetFullPath($RaylexProjectPath)
}

$work = Join-Path $env:TEMP "archigeo-raylex-api-gen"
$buildOut = Join-Path $work "publish"
$mdOut = Join-Path $work "xmldoc"
Remove-Item -Recurse -Force $work -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Path $buildOut, $mdOut -Force | Out-Null

if (-not (Test-Path $RaylexProjectPath)) { throw "Raylex project not found: $RaylexProjectPath" }
dotnet publish $RaylexProjectPath -c Release -f net7.0 -o $buildOut --no-self-contained | Out-Host
if ($LASTEXITCODE -ne 0) { throw "dotnet publish failed" }

$dll = Join-Path $buildOut "ArchiGeoSharp.Raylex.dll"
$xml = Join-Path $buildOut "ArchiGeoSharp.Raylex.xml"
if (-not (Test-Path $dll)) { throw "Missing DLL: $dll" }

$xmldocmd = Get-Command xmldocmd -ErrorAction SilentlyContinue
if (-not $xmldocmd) {
    throw "xmldocmd not found. Install: dotnet tool install -g xmldocmd"
}

xmldocmd $dll $mdOut --source $xml --visibility public | Out-Host
if ($LASTEXITCODE -ne 0) { throw "xmldocmd failed" }

function Read-Utf8 {
    param([string]$Path)
    [System.IO.File]::ReadAllText($Path, [System.Text.Encoding]::UTF8)
}

function Write-Utf8 {
    param([string]$Path, [string]$Content)
    $dir = Split-Path $Path -Parent
    if ($dir) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
    [System.IO.File]::WriteAllText($Path, $Content, [System.Text.UTF8Encoding]::new($false))
}

function Convert-XmlDocLinks {
    param([string]$Text)
    $Text = $Text -replace '\[(?<label>[^\]]+)\]\([^)]+\)', '${label}'
    $Text = $Text -replace '(?m)^<!-- DO NOT EDIT: generated by xmldocmd.*?\r?\n', ''
    return $Text.TrimEnd()
}

function Remove-SeeAlsoSection {
    param([string]$Text)
    return ($Text -replace '(?ms)^## See Also\r?\n.*?(?=\r?\n---\r?\n|\r?\n# |\z)', '').TrimEnd()
}

function Split-MemberMarkdownChunks {
    param([string]$Text)
    $parts = $Text -split '(?m)^---\r?\n\r?\n'
    $chunks = New-Object System.Collections.Generic.List[string]
    foreach ($part in $parts) {
        $t = $part.Trim()
        if ($t.Length -gt 0) { $chunks.Add($t) }
    }
    return $chunks
}

function Normalize-MemberDocHeadings {
    param([string]$Text)
    $Text = $Text -replace '(?m)^# ', '### '
    $Text = $Text -replace '(?m)^## ', '#### '
    return $Text.TrimEnd()
}

function Get-TypeKind {
    param([string]$TypeBody)
    if ($TypeBody -match 'public\s+enum\s+') { return 'enum' }
    if ($TypeBody -match 'public\s+static\s+class\s+') { return 'static' }
    if ($TypeBody -match 'public\s+interface\s+') { return 'interface' }
    if ($TypeBody -match 'public\s+struct\s+') { return 'struct' }
    return 'class'
}

function Get-AssemblyNamespaceSection {
    param([string]$AssemblyMd, [string]$NamespaceHeading)
    $raw = Read-Utf8 $AssemblyMd
    $pattern = "(?ms)(## $([regex]::Escape($NamespaceHeading)) namespace\r?\n.*?)(?=\r?\n## |\z)"
    if ($raw -match $pattern) { return $Matches[1].Trim() }
    return ""
}

function Convert-OverviewTableLinks {
    param([string]$TableMarkdown, [string]$UrlPrefix)
    $lines = $TableMarkdown -split "`r?`n"
    $out = New-Object System.Collections.Generic.List[string]
    foreach ($line in $lines) {
        if ($line -match '^\|\s*(struct|class|interface|static\s+class|abstract\s+class|enum)\s+(.+?)\s*\|') {
            $typeName = $Matches[2].Trim()
            $typeName = $typeName -replace '&lt;', '<' -replace '&gt;', '>'
            $display = $typeName -replace '<.*>', ''
            $fileBase = ($typeName -replace '<', '-' -replace '>', '' -replace '\s', '')
            $line = $line -replace [regex]::Escape($Matches[2]), "[${display}](${UrlPrefix}/${fileBase})"
        }
        $out.Add($line)
    }
    return ($out -join "`n")
}

function Build-TypePageContent {
    param([System.IO.FileInfo]$TypeFile)
    $body = Convert-XmlDocLinks (Read-Utf8 $TypeFile.FullName)
    $body = Remove-SeeAlsoSection $body
    $memberDir = Join-Path $TypeFile.DirectoryName $TypeFile.BaseName
    if (Test-Path $memberDir) {
        $parts = New-Object System.Collections.Generic.List[string]
        $parts.Add($body)
        Get-ChildItem $memberDir -Filter *.md -File | Sort-Object Name | ForEach-Object {
            $rawMember = Read-Utf8 $_.FullName
            foreach ($chunk in (Split-MemberMarkdownChunks $rawMember)) {
                $member = Convert-XmlDocLinks $chunk
                $member = Remove-SeeAlsoSection $member
                $member = $member -replace '(?ms)\r?\n---\s*$', ''
                $member = Normalize-MemberDocHeadings $member
                if ($member.Length -gt 0) { $parts.Add($member) }
            }
        }
        $body = $parts -join "`n`n"
    }
    return $body
}

$assemblyMd = Join-Path $mdOut "ArchiGeoSharp.Raylex.md"
$nsHeading = "ArchiGeo.Raylex"
$nsDir = Join-Path $mdOut "ArchiGeo.Raylex"
$urlPrefix = "/api/raylex"
$title = "ArchiGeo.Raylex"
if (Test-Path $raylexRoot) { Remove-Item -Recurse -Force $raylexRoot }
New-Item -ItemType Directory -Path $raylexRoot -Force | Out-Null

$typeFiles = @()
if (Test-Path $nsDir) {
    $typeFiles = Get-ChildItem $nsDir -Filter *.md -File | Sort-Object Name
}

$kindBuckets = @{
    interface = New-Object System.Collections.Generic.List[object]
    struct    = New-Object System.Collections.Generic.List[object]
    enum      = New-Object System.Collections.Generic.List[object]
    class     = New-Object System.Collections.Generic.List[object]
    static    = New-Object System.Collections.Generic.List[object]
}
$kindLabels = @{
    interface = "Interfaces"
    struct    = "Structs"
    enum      = "Enums"
    class     = "Classes"
    static    = "Static"
}

$nl = [Environment]::NewLine

foreach ($tf in $typeFiles) {
    $base = $tf.BaseName
    $rawType = Read-Utf8 $tf.FullName
    $kind = Get-TypeKind $rawType
    $pageBody = Build-TypePageContent -TypeFile $tf
    $page = "---${nl}outline: [2, 3]${nl}---${nl}${nl}"
    $page += "<p class=""api-breadcrumb""><code>$title</code></p>${nl}${nl}"
    $page += $pageBody + $nl
    Write-Utf8 (Join-Path $raylexRoot "$base.md") $page
    $link = "$urlPrefix/$base"
    $kindBuckets[$kind].Add(@{ text = $base; link = $link }) | Out-Null
}

$overviewLink = "/api/raylex"
$sidebarItems = New-Object System.Collections.Generic.List[object]
$sidebarItems.Add(@{ text = "All types"; link = $overviewLink }) | Out-Null
foreach ($kind in @('interface', 'struct', 'enum', 'class', 'static')) {
    if ($kindBuckets[$kind].Count -eq 0) { continue }
    $sorted = $kindBuckets[$kind] | Sort-Object { $_.text }
    $sidebarItems.Add(@{
        text = $kindLabels[$kind]
        collapsed = $true
        items = $sorted
    }) | Out-Null
}

$toc = Get-AssemblyNamespaceSection -AssemblyMd $assemblyMd -NamespaceHeading $nsHeading
$toc = Convert-XmlDocLinks $toc
$toc = Convert-OverviewTableLinks -TableMarkdown $toc -UrlPrefix $urlPrefix

$overview = "---${nl}outline: false${nl}---${nl}${nl}"
$overview += "# $title${nl}${nl}"
$overview += $toc + $nl
Write-Utf8 $overviewMd $overview
Write-Host ("Wrote overview and {0} type pages under docs/api/raylex/" -f $typeFiles.Count)

function Append-SidebarItemLines {
    param([System.Text.StringBuilder]$Builder, [object]$Item, [int]$Indent)
    $pad = ' ' * $Indent
    $itemText = $Item.text.Replace("'", "\'")
    if ($Item.items -and $Item.items.Count -gt 0) {
        $collapsed = if ($null -ne $Item.collapsed) { $Item.collapsed.ToString().ToLower() } else { 'true' }
        [void]$Builder.AppendLine("${pad}{")
        [void]$Builder.AppendLine("${pad}  text: '$itemText',")
        [void]$Builder.AppendLine("${pad}  collapsed: $collapsed,")
        [void]$Builder.AppendLine("${pad}  items: [")
        foreach ($child in $Item.items) {
            Append-SidebarItemLines -Builder $Builder -Item $child -Indent ($Indent + 4)
        }
        [void]$Builder.AppendLine("${pad}  ]")
        [void]$Builder.AppendLine("${pad}},")
    } else {
        [void]$Builder.AppendLine("${pad}{ text: '$itemText', link: '$($Item.link)' },")
    }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// Auto-generated by scripts/generate-raylex-api.ps1 - do not edit")
[void]$sb.AppendLine("import type { DefaultTheme } from 'vitepress'")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("export const raylexApiSidebarGroup: DefaultTheme.SidebarItem & { partition: string } = {")
[void]$sb.AppendLine("  partition: 'Raylex',")
[void]$sb.AppendLine("  text: 'Raylex',")
[void]$sb.AppendLine("  collapsed: false,")
[void]$sb.AppendLine("  items: [")
foreach ($item in $sidebarItems) {
    Append-SidebarItemLines -Builder $sb -Item $item -Indent 4
}
[void]$sb.AppendLine("  ]")
[void]$sb.AppendLine("}")
Write-Utf8 $sidebarTs $sb.ToString()
Write-Host "Wrote $sidebarTs"
Write-Host "Done."
