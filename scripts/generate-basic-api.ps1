# 从 ArchiGeoSharp.Basic XML 注释生成 docs/api/basic/<ns>/<Type>.md + 侧栏 manifest
# Usage:
#   powershell -File ./scripts/generate-basic-api.ps1
param(
    [string]$BasicProjectPath = "",
    [switch]$FromNuGet,
    [string]$PackageVersion = ""
)

$ErrorActionPreference = "Stop"
$siteRoot = Split-Path $PSScriptRoot -Parent
$docsApi = Join-Path $siteRoot "docs\api"
$basicRoot = Join-Path $docsApi "basic"
$sidebarTs = Join-Path $siteRoot "docs\.vitepress\basic-api-sidebar.ts"

if (-not $BasicProjectPath) {
    $BasicProjectPath = Join-Path $siteRoot "..\ags_v011\src\basic\ArchiGeoSharp.Basic.csproj"
    $BasicProjectPath = [System.IO.Path]::GetFullPath($BasicProjectPath)
}

$work = Join-Path $env:TEMP "archigeo-basic-api-gen"
$buildOut = Join-Path $work "build"
$mdOut = Join-Path $work "xmldoc"
Remove-Item -Recurse -Force $work -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Path $buildOut, $mdOut -Force | Out-Null

function Invoke-BuildFromProject {
    param([string]$ProjectPath, [string]$OutputDir)
    if (-not (Test-Path $ProjectPath)) { throw "Basic project not found: $ProjectPath" }
    dotnet build $ProjectPath -c Release -f net7.0 -o $OutputDir | Out-Host
    if ($LASTEXITCODE -ne 0) { throw "dotnet build failed" }
}

function Invoke-BuildFromNuGet {
    param([string]$OutputDir, [string]$Version)
    if (-not $Version) { throw "-FromNuGet requires -PackageVersion (e.g. 1.0.0)" }
    $nupkgDir = Join-Path $work "nupkg"
    New-Item -ItemType Directory -Path $nupkgDir -Force | Out-Null
    $csproj = @"
<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup><TargetFramework>net7.0</TargetFramework></PropertyGroup>
  <ItemGroup>
    <PackageReference Include="ArchiGeoSharp.Basic" Version="$($Version.TrimStart('/'))" />
  </ItemGroup>
</Project>
"@
    Set-Content -Path (Join-Path $nupkgDir "extract.csproj") -Value $csproj -Encoding UTF8
    dotnet restore (Join-Path $nupkgDir "extract.csproj") | Out-Host
    $globalPackages = Join-Path $env:USERPROFILE ".nuget\packages\archigeosharp.basic\$Version"
    $lib = Get-ChildItem $globalPackages -Recurse -Filter "ArchiGeoSharp.Basic.dll" |
        Where-Object { $_.DirectoryName -match "net7\.0" } | Select-Object -First 1
    if (-not $lib) { throw "Could not locate ArchiGeoSharp.Basic.dll from NuGet $Version" }
    Copy-Item $lib.FullName (Join-Path $OutputDir "ArchiGeoSharp.Basic.dll")
    Copy-Item ($lib.FullName -replace "\.dll$", ".xml") (Join-Path $OutputDir "ArchiGeoSharp.Basic.xml")
}

if ($FromNuGet) {
    Invoke-BuildFromNuGet -OutputDir $buildOut -Version $PackageVersion
} else {
    Invoke-BuildFromProject -ProjectPath $BasicProjectPath -OutputDir $buildOut
}

$dll = Join-Path $buildOut "ArchiGeoSharp.Basic.dll"
$xml = Join-Path $buildOut "ArchiGeoSharp.Basic.xml"
if (-not (Test-Path $dll)) { throw "Missing DLL: $dll" }

xmldocmd $dll $mdOut --source $xml --visibility public | Out-Host
if ($LASTEXITCODE -ne 0) { throw "xmldocmd failed" }

function Read-Utf8 {
    param([string]$Path)
    [System.IO.File]::ReadAllText($Path, [System.Text.Encoding]::UTF8)
}

function Write-Utf8 {
    param([string]$Path, [string]$Content)
    $dir = Split-Path $Path -Parent
    if ($dir) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
    [System.IO.File]::WriteAllText($Path, $Content, [System.Text.UTF8Encoding]::new($false))
}

function Convert-XmlDocLinks {
    param([string]$Text)
    $Text = $Text -replace '\[(?<label>[^\]]+)\]\([^)]+\)', '${label}'
    $Text = $Text -replace '(?m)^<!-- DO NOT EDIT: generated by xmldocmd.*?\r?\n', ''
    return $Text.TrimEnd()
}

function Remove-SeeAlsoSection {
    param([string]$Text)
    # 须在 --- / 下一个 # 标题 前截断（xmldocmd 多重重载写在同一 md 里）
    return ($Text -replace '(?ms)^## See Also\r?\n.*?(?=\r?\n---\r?\n|\r?\n# |\z)', '').TrimEnd()
}

function Split-MemberMarkdownChunks {
    param([string]$Text)
    $parts = $Text -split '(?m)^---\r?\n\r?\n'
    $chunks = New-Object System.Collections.Generic.List[string]
    foreach ($part in $parts) {
        $t = $part.Trim()
        if ($t.Length -gt 0) { $chunks.Add($t) }
    }
    return $chunks
}

function Normalize-MemberDocHeadings {
    param([string]$Text)
    $Text = $Text -replace '(?m)^# ', '### '
    $Text = $Text -replace '(?m)^## ', '#### '
    return $Text.TrimEnd()
}

function Get-TypeKind {
    param([string]$TypeBody)
    if ($TypeBody -match 'public\s+static\s+class\s+') { return 'static' }
    if ($TypeBody -match 'public\s+interface\s+') { return 'interface' }
    if ($TypeBody -match 'public\s+struct\s+') { return 'struct' }
    return 'class'
}

function Get-AssemblyNamespaceSection {
    param([string]$AssemblyMd, [string]$NamespaceHeading)
    $raw = Read-Utf8 $AssemblyMd
    $pattern = "(?ms)(## $([regex]::Escape($NamespaceHeading)) namespace\r?\n.*?)(?=\r?\n## |\z)"
    if ($raw -match $pattern) { return $Matches[1].Trim() }
    return ""
}

function Convert-OverviewTableLinks {
    param([string]$TableMarkdown, [string]$UrlPrefix)
    $lines = $TableMarkdown -split "`r?`n"
    $out = New-Object System.Collections.Generic.List[string]
    foreach ($line in $lines) {
        if ($line -match '^\|\s*(struct|class|interface|static\s+class|abstract\s+class)\s+(.+?)\s*\|') {
            $typeName = $Matches[2].Trim()
            $typeName = $typeName -replace '&lt;', '<' -replace '&gt;', '>'
            $display = $typeName -replace '<.*>', ''
            $fileBase = ($typeName -replace '<', '-' -replace '>', '' -replace '\s', '')
            if ($typeName -match 'WeightedRandomSelector') { $fileBase = 'WeightedRandomSelector-1' }
            if ($typeName -match 'TransCopable') { $fileBase = 'TransCopable-1' }
            $line = $line -replace [regex]::Escape($Matches[2]), "[${display}](${UrlPrefix}/${fileBase})"
        }
        $out.Add($line)
    }
    return ($out -join "`n")
}

function Build-TypePageContent {
    param([System.IO.FileInfo]$TypeFile)
    $body = Convert-XmlDocLinks (Read-Utf8 $TypeFile.FullName)
    $body = Remove-SeeAlsoSection $body
    $memberDir = Join-Path $TypeFile.DirectoryName $TypeFile.BaseName
    if (Test-Path $memberDir) {
        $parts = New-Object System.Collections.Generic.List[string]
        $parts.Add($body)
        Get-ChildItem $memberDir -Filter *.md -File | Sort-Object Name | ForEach-Object {
            $rawMember = Read-Utf8 $_.FullName
            foreach ($chunk in (Split-MemberMarkdownChunks $rawMember)) {
                $member = Convert-XmlDocLinks $chunk
                $member = Remove-SeeAlsoSection $member
                $member = $member -replace '(?ms)\r?\n---\s*$', ''
                $member = Normalize-MemberDocHeadings $member
                if ($member.Length -gt 0) { $parts.Add($member) }
            }
        }
        $body = $parts -join "`n`n"
    }
    return $body
}

function Get-TypeFileBaseName {
    param([System.IO.FileInfo]$f)
    return $f.BaseName
}

$assemblyMd = Join-Path $mdOut "ArchiGeoSharp.Basic.md"

$map = @(
    @{
        Slug = "geometry"
        OverviewFile = "basic-geometry.md"
        Title = "ArchiGeo.Basic.Geometry"
        NsDir = Join-Path $mdOut "ArchiGeo.Basic.Geometry"
        NsHeading = "ArchiGeo.Basic.Geometry"
        OutSubDir = "geometry"
        ExtraTypeFiles = @(
            (Join-Path $mdOut "global\IPlaneExpr.md"),
            (Join-Path $mdOut "global\PlaneExpr.md")
        )
    },
    @{
        Slug = "transform"
        OverviewFile = "basic-transform.md"
        Title = "ArchiGeo.Basic.Transform"
        NsDir = Join-Path $mdOut "ArchiGeo.Basic.Transform"
        NsHeading = "ArchiGeo.Basic.Transform"
        OutSubDir = "transform"
        ExtraTypeFiles = @()
    },
    @{
        Slug = "numeric"
        OverviewFile = "basic-numeric.md"
        Title = "ArchiGeo.Basic.Numeric"
        NsDir = Join-Path $mdOut "ArchiGeo.Basic.Numeric"
        NsHeading = "ArchiGeo.Basic.Numeric"
        OutSubDir = "numeric"
        ExtraTypeFiles = @()
    },
    @{
        Slug = "topology"
        OverviewFile = "basic-topology.md"
        Title = "ArchiGeo.Basic.Topology"
        NsDir = Join-Path $mdOut "ArchiGeo.Basic.Topology"
        NsHeading = "ArchiGeo.Basic.Topology"
        OutSubDir = "topology"
        ExtraTypeFiles = @()
    }
)

# 清理旧版单文件巨页
@("basic-geometry.md", "basic-transform.md", "basic-numeric.md", "basic-topology.md") | ForEach-Object {
    $p = Join-Path $docsApi $_
    if (Test-Path $p) { Remove-Item $p -Force }
}
if (Test-Path $basicRoot) { Remove-Item -Recurse -Force $basicRoot }
New-Item -ItemType Directory -Path $basicRoot -Force | Out-Null

$sidebarGroups = New-Object System.Collections.Generic.List[object]

$nl = [Environment]::NewLine

foreach ($entry in $map) {
    $typeFiles = @()
    if (Test-Path $entry.NsDir) {
        $typeFiles += Get-ChildItem $entry.NsDir -Filter *.md -File
    }
    foreach ($extra in $entry.ExtraTypeFiles) {
        if (Test-Path $extra) { $typeFiles += Get-Item $extra }
    }
    $typeFiles = $typeFiles | Sort-Object Name -Unique
    $urlPrefix = "/api/basic/$($entry.OutSubDir)"
    $outDir = Join-Path $basicRoot $entry.OutSubDir

    $overviewLink = "/api/$($entry.OverviewFile -replace '\.md$','')"
    $kindBuckets = @{
        interface = New-Object System.Collections.Generic.List[object]
        struct    = New-Object System.Collections.Generic.List[object]
        class     = New-Object System.Collections.Generic.List[object]
        static    = New-Object System.Collections.Generic.List[object]
    }
    $kindLabels = @{
        interface = "Interfaces"
        struct    = "Structs"
        class     = "Classes"
        static    = "Static"
    }

    foreach ($tf in $typeFiles) {
        $base = Get-TypeFileBaseName $tf
        $rawType = Read-Utf8 $tf.FullName
        $kind = Get-TypeKind $rawType
        $pageBody = Build-TypePageContent -TypeFile $tf
        $page = "---${nl}outline: [2, 3]${nl}---${nl}${nl}"
        $page += "<p class=""api-breadcrumb""><code>$($entry.Title)</code></p>${nl}${nl}"
        $page += $pageBody + $nl
        Write-Utf8 (Join-Path $outDir "$base.md") $page
        $link = "$urlPrefix/$base"
        $kindBuckets[$kind].Add(@{ text = $base; link = $link }) | Out-Null
    }

    # 左侧二级：命名空间 -> (Interfaces / Structs / Classes / Static) -> 类型
    $sidebarItems = New-Object System.Collections.Generic.List[object]
    $sidebarItems.Add(@{ text = "All types"; link = $overviewLink }) | Out-Null
    foreach ($kind in @('interface', 'struct', 'class', 'static')) {
        if ($kindBuckets[$kind].Count -eq 0) { continue }
        $sorted = $kindBuckets[$kind] | Sort-Object { $_.text }
        $sidebarItems.Add(@{
            text = $kindLabels[$kind]
            collapsed = $true
            items = $sorted
        }) | Out-Null
    }

    $toc = Get-AssemblyNamespaceSection -AssemblyMd $assemblyMd -NamespaceHeading $entry.NsHeading
    $toc = Convert-XmlDocLinks $toc
    $toc = Convert-OverviewTableLinks -TableMarkdown $toc -UrlPrefix $urlPrefix

    $overview = "---${nl}outline: false${nl}---${nl}${nl}"
    $overview += "# $($entry.Title)${nl}${nl}"
    $overview += $toc + $nl
    Write-Utf8 (Join-Path $docsApi $entry.OverviewFile) $overview
    Write-Host ('Wrote overview and ' + $typeFiles.Count + ' types for ' + $entry.Slug)

    $label = switch ($entry.Slug) {
        "geometry" { "Basic.Geometry" }
        "transform" { "Basic.Transform" }
        "numeric" { "Basic.Numeric" }
        "topology" { "Basic.Topology" }
        default { "Basic.$($entry.Slug)" }
    }
    $sidebarGroups.Add(@{
        text = $label
        collapsed = $false
        items = $sidebarItems
    }) | Out-Null
}

# 生成 VitePress 侧栏片段
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// Auto-generated by scripts/generate-basic-api.ps1 - do not edit")
[void]$sb.AppendLine("import type { DefaultTheme } from 'vitepress'")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("export const basicApiSidebar: DefaultTheme.SidebarItem[] = [")

function Append-SidebarItemLines {
    param([System.Text.StringBuilder]$Builder, [object]$Item, [int]$Indent)
    $pad = ' ' * $Indent
    $itemText = $Item.text.Replace("'", "\'")
    if ($Item.items -and $Item.items.Count -gt 0) {
        $collapsed = if ($null -ne $Item.collapsed) { $Item.collapsed.ToString().ToLower() } else { 'true' }
        [void]$Builder.AppendLine("${pad}{")
        [void]$Builder.AppendLine("${pad}  text: '$itemText',")
        [void]$Builder.AppendLine("${pad}  collapsed: $collapsed,")
        [void]$Builder.AppendLine("${pad}  items: [")
        foreach ($child in $Item.items) {
            Append-SidebarItemLines -Builder $Builder -Item $child -Indent ($Indent + 4)
        }
        [void]$Builder.AppendLine("${pad}  ]")
        [void]$Builder.AppendLine("${pad}},")
    } else {
        [void]$Builder.AppendLine("${pad}{ text: '$itemText', link: '$($Item.link)' },")
    }
}

foreach ($group in $sidebarGroups) {
    [void]$sb.AppendLine("  {")
    $groupText = $group.text.Replace("'", "\'")
    [void]$sb.AppendLine("    text: '$groupText',")
    [void]$sb.AppendLine("    collapsed: false,")
    [void]$sb.AppendLine("    items: [")
    foreach ($item in $group.items) {
        Append-SidebarItemLines -Builder $sb -Item $item -Indent 6
    }
    [void]$sb.AppendLine("    ]")
    [void]$sb.AppendLine("  },")
}
[void]$sb.AppendLine("]")
Write-Utf8 $sidebarTs $sb.ToString()
Write-Host "Wrote $sidebarTs"
Write-Host "Done."
